async function runTest() {
  console.log('=== กำลังนำเข้าแชทปัญหา 5 ชุด (ไม่มีการพนัน) เข้าสู่ Supabase ===\n');

  for (const chat of cleanChats) {
    console.log(`- กำลังบันทึก [${chat.id}] หมวด: ${chat.category_id} (Priority: ${chat.priority})...`);
    
    // Upsert to prevent duplicate key conflicts
    const { data, error } = await supabase
      .from('chats')
      .upsert(chat, { onConflict: 'id' })
      .select('id, category_id, priority, status');

    if (error) {
      console.error(`  ❌ บันทึก ${chat.id} ไม่สำเร็จ:`, error.message);
    } else {
      console.log(`  ✅ บันทึกสำเร็จ: ${chat.id} (Status: ${data[0].status})`);
    }
  }

  console.log('\n=== ตรวจสอบข้อมูลจาก Supabase ที่เพิ่งบันทึก ===');
  const { data: verifyData, error: verifyError } = await supabase
    .from('chats')
    .select('id, customer_id, category_id, priority, summary, status')
    .in('id', cleanChats.map(c => c.id));

  if (verifyError) {
    console.error('❌ ดึงข้อมูลมาตรวจสอบไม่สำเร็จ:', verifyError.message);
  } else {
    console.log(`✅ พบข้อมูลใน Supabase ทั้งหมด ${verifyData.length} แชท:`);
    console.table(verifyData);
  }
}

runTest();
