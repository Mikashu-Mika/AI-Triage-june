function sleep(ms) {
  return new Promise(resolve => setTimeout(resolve, ms));
}

async function runStreamPipeline() {
  console.log('===============================================================');
  console.log('🚀 เริ่มต้นยิงชุดปัญหาลูกค้า 10 ชุด (เว้นช่วงชุดละ 2 นาที)');
  console.log(`🏢 บริษัทเป้าหมาย: Mika Co. (${COMPANY_ID})`);
  console.log(`⏱️ ระยะห่างระหว่างปัญหา: ${DELAY_SECONDS} วินาที (2 นาที)`);
  console.log('===============================================================\n');

  // 1. Ensure customers exist
  for (const c of cleanCustomerChats) {
    await supabase.from('customers').upsert({
      id: c.customer_id,
      name: c.customer_name,
      phone: null,
      email: null
    });
  }

  for (let i = 0; i < cleanCustomerChats.length; i++) {
    const item = cleanCustomerChats[i];
    const timestamp = new Date().toLocaleTimeString('th-TH');
    const startOverall = Date.now();

    console.log(`\n---------------------------------------------------------------`);
    console.log(`[${timestamp}] 📩 ยิงชุดปัญหาที่ ${i + 1}/10: "${item.id}" (ลูกค้า: ${item.customer_name})`);
    console.log(`📄 เนื้อหาแชต:\n${item.conversation.split('\n').map(l => '   ' + l).join('\n')}`);

    // Insert as pending
    const { error: insErr } = await supabase.from('chats').upsert({
      id: item.id,
      customer_id: item.customer_id,
      company_id: COMPANY_ID,
      conversation: item.conversation,
      status: 'pending'
    });

    if (insErr) {
      console.error(`❌ บันทึกแชต ${item.id} ลง Supabase ล้มเหลว:`, insErr.message);
      continue;
    }
    console.log(`✅ บันทึกสถานะ Pending ลง Supabase เรียบร้อย`);

    // Run AI Triage through Ollama (Qwen 2.5 14B + BGE-M3)
    console.log(`🤖 กำลังให้ Ollama (Qwen 2.5 14B) วิเคราะห์และจัดหมวดหมู่อย่างละเอียด...`);
    const triageStart = Date.now();
    try {
      await processSingleChat(item.id);
      const triageDuration = ((Date.now() - triageStart) / 1000).toFixed(1);
      console.log(`✅ Ollama วิเคราะห์สำเร็จใน ${triageDuration} วินาที!`);

      // Query result from Supabase to log summary
      const { data: result } = await supabase
        .from('chats')
        .select('category_id, priority, summary, chat_issues(*)')
        .eq('id', item.id)
        .single();

      console.log(`   📌 หมวดหลัก: ${result?.category_id} | ระดับความเร่งด่วน: ${result?.priority}`);
      console.log(`   📝 สรุป: ${result?.summary}`);
      console.log(`   🔍 ประเด็นย่อยใน chat_issues (${result?.chat_issues?.length || 0} เรื่อง):`);
      result?.chat_issues?.forEach((iss, idx) => {
        console.log(`      ${idx + 1}. [${iss.category_id}] (${iss.priority}): "${iss.summary}"`);
      });

    } catch (err) {
      console.error(`❌ การวิเคราะห์โดย Ollama สำหรับ ${item.id} ขัดข้อง:`, err.message);
    }

    // Wait 2 minutes (120 seconds) before sending the next one if not last
    if (i < cleanCustomerChats.length - 1) {
      const elapsedSeconds = Math.round((Date.now() - startOverall) / 1000);
      const remainingSeconds = Math.max(0, DELAY_SECONDS - elapsedSeconds);
      console.log(`\n⏳ รอระยะห่างตามรอบ 2 นาที (รออีก ${remainingSeconds} วินาที) ก่อนส่งปัญหาชุดที่ ${i + 2}...`);
      await sleep(remainingSeconds * 1000);
    }
  }

  console.log('\n===============================================================');
  console.log('🎉 ยิงและวิเคราะห์ชุดปัญหาครบทั้ง 10 ชุดเรียบร้อยสมบูรณ์แล้ว!');
  console.log('===============================================================');
}

runStreamPipeline().catch(console.error);
